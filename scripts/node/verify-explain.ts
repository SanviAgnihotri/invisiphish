/**
 * Probe the explanation layer through the application's own code path.
 *
 * It runs the real detection pipeline over a few messages, aggregates the
 * evidence exactly the way `/api/analyze` does, and hands that evidence to
 * the same `explainFromEvidence` the `/api/explain` route calls. It then
 * prints the generated explanation and the groundedness report, so the claim
 * the paper makes - that every claim is traceable to computed evidence - can
 * be checked on the machine rather than taken on trust.
 *
 * The point of the groundedness report is that it is computed from the
 * evidence table, not from the model's self-assessment: a bullet that cites
 * an id the pipeline never produced is dropped and counted.
 */
import { aggregate } from '../../src/lib/ml/aggregation';
import { runIntentModule } from '../../src/lib/ml/intentAnalysis';
import { runPatternModule } from '../../src/lib/ml/patternModule';
import { runSemanticModule } from '../../src/lib/ml/semanticModel';
import { runUrlModule } from '../../src/lib/ml/urlIntel';
import { explainFromEvidence } from '../../api/_lib/explain';

const SAMPLES = [
  {
    label: 'phishing',
    text: 'URGENT: Your account has been suspended. Verify your identity immediately at http://192.168.0.1/verify to avoid permanent closure.',
  },
  {
    label: 'legitimate',
    text: 'Hi Sarah, the meeting notes from Tuesday are attached. Let me know if you want me to walk through the Q3 numbers.',
  },
];

console.log('== InvisiPhish explanation layer ==\n');
console.log('provider  :', process.env.EXPLAIN_PROVIDER ?? 'opencode');
console.log(
  'models    :',
  (process.env.OPENCODE_MODELS ??
    'glm-5.3-flash,mimo-v2.6-flash,qwen3.8-flash,mimo-v2.5,hy3,longcat-2.0')
    .split(',')
    .map((model) => model.trim())
    .filter(Boolean)
    .join(' -> '),
);
console.log('api key   :', process.env.OPENCODE_API_KEY ? 'configured' : 'MISSING');
console.log();

for (const sample of SAMPLES) {
  const semantic = await runSemanticModule(sample.text);
  const intent = runIntentModule(sample.text);
  const url = runUrlModule(sample.text);
  const pattern = await runPatternModule(sample.text, []);
  const aggregated = aggregate([semantic, intent, url, pattern]);

  const started = Date.now();
  const outcome = await explainFromEvidence(
    aggregated.rankedEvidence,
    aggregated.verdict,
    aggregated.finalScore,
  );
  const elapsed = Date.now() - started;

  console.log('---', sample.label, '|', sample.text.slice(0, 56));
  console.log(
    '    verdict       :',
    aggregated.verdict,
    `(${(aggregated.finalScore * 100).toFixed(1)}%)`,
  );
  console.log('    evidence      :', aggregated.rankedEvidence.length, 'items');
  console.log('    generated by  :', outcome.generated ? (outcome.model ?? 'model') : 'FALLBACK');
  console.log('    latency       :', `${elapsed} ms`);
  console.log('    summary       :', outcome.explanation.summary);
  for (const bullet of outcome.explanation.bullets) {
    console.log(`      - ${bullet.text}  [${bullet.evidenceIds.join(', ')}]`);
  }
  for (const action of outcome.explanation.recommendedActions) {
    console.log('      *', action);
  }
  console.log(
    '    groundedness  :',
    `${(outcome.groundedness.score * 100).toFixed(1)}%`,
    `(${outcome.groundedness.validBullets} valid, ${outcome.groundedness.invalidBullets} dropped)`,
  );
  if (outcome.groundedness.droppedBullets.length > 0) {
    for (const dropped of outcome.groundedness.droppedBullets) {
      console.log('      dropped:', dropped.text, '-', dropped.reason);
    }
  }
  if (outcome.groundedness.unknownEvidenceIds.length > 0) {
    console.log('      unknown ids:', outcome.groundedness.unknownEvidenceIds.join(', '));
  }
  console.log();
}

if (!process.env.OPENCODE_API_KEY && (process.env.EXPLAIN_PROVIDER ?? 'opencode') === 'opencode') {
  console.log('No OPENCODE_API_KEY: the deterministic fallback was used, not the model.');
  process.exit(1);
}
